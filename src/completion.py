"""Generate the bash completion script from the argparse parser, so options are never listed twice.

Regenerate after changing src/parser.py (from the project root):
    Xvenv/bin/python -m src.completion > completions/grox.bash
"""
from src.parser import build_parser

PROG = "GroX.sh"   # the command the completion is registered for


def generate():
    parser = build_parser()

    flags = []      # every option string, e.g. --display, --no-wait-login
    choices = {}    # option string -> fixed values (e.g. --page-load -> normal eager)
    free_form = []  # options that take a value we cannot suggest (numbers, names)

    # argparse has no public API to list the actions of a parser.
    for action in parser._actions:
        for flag in action.option_strings:
            flags.append(flag)
            if action.nargs == 0:
                continue                       # a plain switch: takes no value
            if action.choices:
                choices[flag] = list(action.choices)
            else:
                free_form.append(flag)

    case_lines = [
        f'        {flag}) COMPREPLY=( $(compgen -W "{" ".join(values)}" -- "$cur") ); return ;;'
        for flag, values in choices.items()
    ]
    if free_form:
        case_lines.append(f'        {"|".join(free_form)}) return ;;   # free-form value: nothing to suggest')

    lines = [
        "# Generated by `python -m src.completion` from src/parser.py. Do not edit by hand.",
        "_grox_complete() {",
        "    local cur prev",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        "",
        '    case "$prev" in',
        *case_lines,
        "    esac",
        "",
        f'    COMPREPLY=( $(compgen -W "{" ".join(flags)}" -- "$cur") )',
        "}",
        "",
        f"complete -F _grox_complete {PROG}",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(generate(), end="")